def fn(f): return f"<Filename>{x(f)}</Filename>"
def cat(c): return f"<Category>{x(c)}</Category>"

def rule_xml(r, extra_excl=()):
    parts = [fn(f) for f in r.get("files", [])]
    guards = []
    if r.get("not_cats"): guards.append("<Not><Or>" + "".join(cat(c) for c in r["not_cats"]) + "</Or></Not>")
    nf = list(r.get("not_files", [])) + list(extra_excl)
    if nf: guards.append("<Not><Or>" + "".join(fn(f) for f in nf) + "</Or></Not>")
    g = "".join(guards)
    if r.get("cats_any"):
        parts.append("<And><Or>" + "".join(cat(c) for c in r["cats_any"]) + "</Or>" + g + "</And>")
    for grp in r.get("cats_all", []):
        parts.append("<And>" + "".join(cat(c) for c in grp) + g + "</And>")
    inc = "<Include><Or>" + "".join(parts) + "</Or></Include>" if parts else ""
    excl = "<Exclude>" + "".join(fn(f) for f in HIDDEN) + "</Exclude>"
    return inc + excl

def directory(did, name, comment, icon):
    with open(os.path.join(OUT, "desktop-directories", f"laden-{did}.directory"), "w") as f:
        f.write(f"[Desktop Entry]\nType=Directory\nName={name}\nComment={comment}\nIcon={icon}\n")
    return f"laden-{did}.directory"

def menu(name, dirfile, body, sub=""):
    return f"<Menu><Name>{x(name)}</Name><Directory>{dirfile}</Directory>{body}{sub}</Menu>\n"

xml = ['<!DOCTYPE Menu PUBLIC "-//freedesktop//DTD Menu 1.0//EN"\n "http://www.freedesktop.org/standards/menu-spec/1.0/menu.dtd">',
       "<!-- Laden OS application menu. Generated by packages/laden-menu/gen.py: edit menu-spec.py. -->",
       "<Menu>\n<Name>Applications</Name>"]
for s in STOCK:  # hide the stock top-level folders; Laden ones replace them
    xml.append(f"<Menu><Name>{s}</Name><Deleted/></Menu>")
order = []
for tid, name, comment, r in spec["TOP"]:
    d = directory(tid, name, comment, f"laden-category-{tid}")
    mname = f"Laden-{tid}"; order.append(mname)
    if r.get("rt"):
        subs = ""
        for sid, sname, scomment in spec["RT_SUBS"]:
            sd = directory(f"redteam-{sid}", sname, scomment, f"laden-redteam-{sid}")
            inc = "<Include><Or>" + "".join(fn(f) for f in RT_GUI.get(sid, [])) + cat(f"X-Laden-RedTeam-{sid}") + "</Or></Include>"
            subs += menu(f"Laden-redteam-{sid}", sd, inc)
        body = "<Include>" + fn("laden-redteam-shell.desktop") + "</Include>"
        xml.append(menu(mname, d, body, subs))
    elif r.get("subs"):
        subs = ""
        for sid, sname, scomment, sr in r["subs"]:
            sd = directory(f"{tid}-{sid}", sname, scomment, f"laden-category-{tid}-{sid}")
            subs += menu(f"Laden-{tid}-{sid}", sd, rule_xml(sr, RT_NON_TUNNEL))
        xml.append(menu(mname, d, "", subs))
    else:
        xml.append(menu(mname, d, rule_xml(r, RT_NON_TUNNEL if tid != "redteam" else ())))
d = directory("more", "More", "Everything else", "laden-category-more")
xml.append(menu("Laden-more", d, "<OnlyUnallocated/><Include><All/></Include><Exclude>" + "".join(fn(f) for f in HIDDEN) + "</Exclude>"))
order.append("Laden-more")
xml.append("<Layout>" + "".join(f"<Menuname>{m}</Menuname>" for m in order) + '<Merge type="menus"/><Merge type="files"/></Layout>')
xml.append("</Menu>")
open(os.path.join(OUT, "menus", "laden.menu"), "w").write("\n".join(xml) + "\n")

