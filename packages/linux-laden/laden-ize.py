#!/usr/bin/env python3
"""Turn CachyOS's linux-cachyos PKGBUILD into linux-laden.

Same sources, patches, compiler (clang ThinLTO), config and march (x86-64-v3) as
the CachyOS binary package. Only the name changes:
  pkgbase linux-laden, uname -r <ver>-<rel>-laden, build host "laden".
Usage: laden-ize.py <upstream PKGBUILD> <out PKGBUILD> <upstream commit>
"""
import re, sys
src, out, commit = sys.argv[1:4]
s = open(src).read()

def sub(pat, rep, count=1, flags=re.M):
    global s
    n = len(re.findall(pat, s, flags))
    if n < 1:
        sys.exit(f"laden-ize: pattern not found (upstream changed?): {pat}")
    s = re.sub(pat, rep, s, count=count if count else 0, flags=flags)

header = f"""# Maintainer: Laden OS Repo <admin@laden.no>
#
# linux-laden: the CachyOS kernel compiled from CachyOS's own sources under the
# Laden name. Generated by laden-ize.py from CachyOS/linux-cachyos
# (linux-cachyos/PKGBUILD @ {commit}); do not edit by hand, run
# update-from-cachyos.sh instead.
#   - config: the exact .config of the CachyOS x86_64_v3 binary (file "config")
#   - x86-64-v3, clang ThinLTO, AutoFDO-enabled build, 1000 Hz, full tickless,
#     PREEMPT_DYNAMIC, sched_ext; same patches and toolchain as CachyOS
#   - uname -r: <ver>-<rel>-laden, pkgbase linux-laden
# CachyOS maintainers and contributors credited below.
#
"""
s = header + s

# CachyOS v3 repo build options (script-v3-v4.sh) + AutoFDO as in the binary config
sub(r'^: "\$\{_processor_opt:=\}"', ': "${_processor_opt:=GENERIC_V3}"')
sub(r'^: "\$\{_autofdo:=no\}"', ': "${_autofdo:=yes}"')

# Name
sub(r'^pkgbase="linux-\$_pkgsuffix"', '_pkgsuffix=laden\npkgbase=linux-laden')
sub(r"^pkgdesc='Linux EEVDF[^']*'", "pkgdesc='Laden OS kernel: CachyOS EEVDF + ThinLTO + AutoFDO, x86-64-v3, built from CachyOS sources'")
sub(r'^url=.*$', 'url="https://laden.no"')
# epoch 1: supersedes the earlier repackaged-binary linux-laden of the same version
sub(r'^pkgrel=(.*)$', r'pkgrel=\1\nepoch=1')
sub(r'^export KBUILD_BUILD_HOST=cachyos', 'export KBUILD_BUILD_HOST=laden')

# No linux-cachyos-lto provides/replaces: the module dir differs, both kernels can coexist
sub(r'^\s*provides\+=\(linux-cachyos-lto=\$_kernver\)\n\s*replaces=\(linux-cachyos-lto\)\n', '        : # Laden: no linux-cachyos-lto provides/replaces (own module dir)\n', count=0)
sub(r'^\s*provides\+=\(linux-cachyos-lto-headers=\$_kernver\)\n\s*replaces=\(linux-cachyos-lto-headers\)\n', '        : # Laden: no linux-cachyos-lto-headers provides/replaces\n', count=0)
if re.search(r'[(=]linux-cachyos-lto', s):
    sys.exit("laden-ize: leftover linux-cachyos-lto reference")

# Parallel jobs can be capped from outside (LADEN_JOBS), default nproc as upstream
s = s.replace('-j"$(nproc)"', '-j"${LADEN_JOBS:-$(nproc)}"')

# After the config rewrite, show how far we are from the CachyOS binary config
sub(r'^(\s*)diff -u \.\./config \.config \|\| :', r'''\1diff -u ../config .config || :
\1if ! diff -q <(grep -v '^#' ../config | sort) <(grep -v '^#' .config | sort) >/dev/null; then
\1    warning "linux-laden: .config differs from the CachyOS binary config (see diff above)"
\1fi''')

open(out, "w").write(s)
print(f"wrote {out}")
